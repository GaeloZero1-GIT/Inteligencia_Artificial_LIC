import numpy as np
import matplotlib.pyplot as plt
import random

# 1. Hiperparámetros y configuración inicial

alpha = 0.5
gamma = 1.0
epsilon = 0.1
episodes = 500
max_steps = 200
seed = 42  # Semilla fija

random.seed(seed)
np.random.seed(seed)

# Dimensiones y coordenadas clave
ROWS, COLS = 4, 12
START = (3, 0)
GOAL = (3, 11)

# Acciones: 0:Norte, 1:Este, 2:Sur, 3:Oeste
ACTIONS = [(-1, 0), (0, 1), (1, 0), (0, -1)]
ACTION_SYMBOLS = ['↑', '→', '↓', '←']

# 2. Definición del entorno

def step(state, action_idx):
    r, c = state
    dr, dc = ACTIONS[action_idx]
    nr, nc = r + dr, c + dc

    # Chocar con los límites: el agente se queda en el mismo lugar
    if nr < 0 or nr >= ROWS or nc < 0 or nc >= COLS:
        nr, nc = r, c

    next_state = (nr, nc)

    # Caer al acantilado
    if next_state[0] == 3 and 1 <= next_state[1] <= 10:
        return START, -100, False

    # Llegar a la Meta (G)
    if next_state == GOAL:
        return next_state, -1, True

    return next_state, -1, False

# 3. Algoritmo Q-learning

# Inicializar Q(s, a) en 0 para todo par estado-acción
Q = {((r, c), a): 0.0 for r in range(ROWS) for c in range(COLS) for a in range(4)}

def get_best_action(state):
    q_values = [Q[(state, a)] for a in range(4)]
    max_q = max(q_values)
    return q_values.index(max_q)

def epsilon_greedy(state):
    if random.random() < epsilon:
        return random.randint(0, 3)
    else:
        return get_best_action(state)

# Bucle de Entrenamiento
rewards_per_episode = []

for ep in range(episodes):
    state = START
    total_reward = 0

    for _ in range(max_steps):
        action = epsilon_greedy(state)
        next_state, reward, done = step(state, action)
        total_reward += reward

        if done:
            max_q_next = 0.0
        else:
            max_q_next = max([Q[(next_state, a)] for a in range(4)])

        # Ecuación principal de actualización Q-learning
        Q[(state, action)] = Q[(state, action)] + alpha * (reward + gamma * max_q_next - Q[(state, action)])

        state = next_state
        if done:
            break

    rewards_per_episode.append(total_reward)

# 4. Evaluación de la política
eval_state = START
eval_return = 0
greedy_path = [eval_state]

for _ in range(max_steps):
    if eval_state == GOAL: break
    best_a = get_best_action(eval_state)
    nxt_s, r, d = step(eval_state, best_a)
    eval_return += r
    eval_state = nxt_s
    greedy_path.append(eval_state)

print(f"Semilla utilizada: {seed}")
print(f"Retorno de la política greedy óptima: {eval_return}")
print(f"Número de pasos S -> G: {len(greedy_path)-1}")

print("\nCuadrícula de la política greedy (Flechas):")
for r in range(ROWS):
    row_str = ""
    for c in range(COLS):
        if (r, c) == START: row_str += "S  "
        elif (r, c) == GOAL: row_str += "G  "
        elif r == 3 and 1 <= c <= 10: row_str += "C  "
        else: row_str += f"{ACTION_SYMBOLS[get_best_action((r, c))]}  "
    print(row_str)


# 5. Gráfica
window = 10
moving_avg = np.convolve(rewards_per_episode, np.ones(window)/window, mode='valid')

plt.figure(figsize=(10, 5))
plt.plot(rewards_per_episode, alpha=0.3, color='gray', label='Recompensa cruda por episodio')
plt.plot(range(window-1, len(rewards_per_episode)), moving_avg, color='blue', label=f'Media Móvil (n={window})')
plt.ylim(-200, 0)
plt.xlabel('Episodios')
plt.ylabel('Recompensa (Retorno Acumulado)')
plt.title('Curva de Entrenamiento Q-learning (Cliff Walking)')
plt.legend()
plt.grid(True)
plt.savefig('curva_qlearning.png', dpi=150)